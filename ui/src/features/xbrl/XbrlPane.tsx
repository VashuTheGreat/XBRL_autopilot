import { Braces, Eye, Table2 } from 'lucide-react'
import { EmptyState } from '@/components/EmptyState'
import { Tabs } from '@/components/Tabs'
import { useUi } from '@/stores/ui'

/** Right editor: XBRL Form (ELR grid), live XML (Monaco) and MCA-like preview. */
export function XbrlPane() {
  const { rightTab, setRightTab } = useUi()
  return (
    <section className="flex h-full flex-col bg-panel" aria-label="XBRL">
      <Tabs
        value={rightTab}
        onChange={setRightTab}
        tabs={[
          { id: 'form', label: 'XBRL Form' },
          { id: 'xml', label: 'XML' },
          { id: 'preview', label: 'Preview' },
        ]}
      />
      <div className="min-h-0 flex-1">
        {rightTab === 'form' && (
          <EmptyState icon={Table2} title="XBRL Form" phase="Phase 4">
            Taxonomy statements and dimensional tables with the tagged facts. Selecting a fact highlights its source
            Excel cell.
          </EmptyState>
        )}
        {rightTab === 'xml' && (
          <EmptyState icon={Braces} title="Instance XML" phase="Phase 4">
            The live, deterministic instance document generated by the engine.
          </EmptyState>
        )}
        {rightTab === 'preview' && (
          <EmptyState icon={Eye} title="Preview" phase="Phase 6">
            An MCA-like rendering of the filing, exportable to PDF.
          </EmptyState>
        )}
      </div>
    </section>
  )
}
