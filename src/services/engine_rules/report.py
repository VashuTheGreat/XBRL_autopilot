"""``docs/generated/rule-coverage-<kb>.md``: every MCA business rule of a taxonomy with its engine status."""
from __future__ import annotations

from collections import Counter

_LABEL = {
    "EXECUTABLE": "formalized",
    "REVIEW_ONLY_EXTERNAL_DATA": "review-only",
    "UNIMPLEMENTED": "missing",
    "NOT_APPLICABLE": "not applicable",
}


def _cell(s) -> str:
    if s is None:
        return ""
    if isinstance(s, list):
        s = ", ".join(str(x) for x in s)
    return str(s).replace("|", "\\|").replace("\n", " ")


def _status(c: dict) -> str:
    if c.get("approvedLimitation"):
        return "approved-limitation"
    return _LABEL.get(c["status"], c["status"])


def coverage_markdown(spec, coverage: dict) -> str:
    m = coverage["measure"]
    rules = coverage["rules"]
    out = [
        f"# Rule coverage · {spec.title}",
        "",
        f"> Generated by `make engine-rules` from `{coverage['source']}` (sha256 `{coverage['corpus']['sourceSha256'][:12]}`). Do not edit.",
        "> Statuses: **formalized** (executed by the engine), **review-only** (needs MCA21 master data or another instance),",
        "> **missing** (not formalized: backlog), **approved-limitation**, **not applicable** (no executable content in this taxonomy).",
        "",
        "## Summary",
        "",
        "| Measure | Value |",
        "|---|---|",
        f"| Rules (all sheets) | {m['rules']} |",
        f"| Not applicable | {m['notApplicable']} |",
        f"| Counted (all − not applicable) | {m['denominator']} |",
        f"| Formalized | {m['executable']} |",
        f"| Review-only | {m['reviewOnly']} |",
        f"| Missing | {m['unimplemented']} |",
        f"| Approved limitations | {m['approvedLimitations']} |",
        f"| **Executable share** (formalized ÷ counted) | **{m['executableShare']:.1%}** |",
        "",
        "## By family",
        "",
        "| Family | formalized | review-only | missing | not applicable |",
        "|---|---|---|---|---|",
    ]
    fam: dict[str, Counter] = {}
    for c in rules:
        fam.setdefault(c["family"], Counter())[c["status"]] += 1
    for f, cnt in fam.items():
        out.append(f"| {f} | {cnt['EXECUTABLE']} | {cnt['REVIEW_ONLY_EXTERNAL_DATA']} | {cnt['UNIMPLEMENTED']} | {cnt['NOT_APPLICABLE']} |")

    def section(title: str, rows: list[dict], cols: list[tuple[str, str]]) -> None:
        out.extend(["", f"## {title} ({len(rows)})", ""])
        if not rows:
            out.append("None.")
            return
        out.append("| " + " | ".join(h for h, _ in cols) + " |")
        out.append("|" + "---|" * len(cols))
        for c in rows:
            out.append("| " + " | ".join(_cell(c.get(k)) for _, k in cols) + " |")

    base = [("Rule", "ruleId"), ("Row", "sourceRow"), ("Element", "element"), ("Clause", "clause")]
    section("Missing (backlog)", [c for c in rules if c["status"] == "UNIMPLEMENTED"], [*base, ("Reason", "reason")])
    section("Downgraded by evidence (warning)", [c for c in rules if c.get("divergence")], [*base, ("Evidence", "divergence")])
    section("Review-only", [c for c in rules if c["status"] == "REVIEW_ONLY_EXTERNAL_DATA"], [*base, ("Reason", "reason")])
    section("Not applicable", [c for c in rules if c["status"] == "NOT_APPLICABLE"], [*base, ("Reason", "reason")])
    section("Formalized", [c for c in rules if c["status"] == "EXECUTABLE"], [*base, ("Implementation", "implementation")])
    return "\n".join(out) + "\n"
